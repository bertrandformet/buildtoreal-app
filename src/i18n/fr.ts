export type Key = keyof typeof fr;
type Params = Record<string, string | number>;

/** Pluriel minimal : « {n, plural, one {…} other {…}} », « # » = nombre. */
function plural(text: string, params: Params): string {
  return text.replace(/\{(\w+), plural, one \{([^}]*)\} other \{([^}]*)\}\}/g, (_m, name: string, one: string, other: string) => {
    const n = Number(params[name] ?? 0);
    return (n === 1 ? one : other).replace('#', String(n));
  });
}

export function t(key: Key, params: Params = {}): string {
  let text: string = fr[key];
  text = plural(text, params);
  return text.replace(/\{(\w+)\}/g, (_m, name: string) => String(params[name] ?? ''));
}
